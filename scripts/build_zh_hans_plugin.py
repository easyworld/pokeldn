"""Export this fork's Chinese resources as an upstream API 1.9 data-only plugin.

Usage: python scripts/build_zh_hans_plugin.py --upstream build/upstream-language-preview
The upstream checkout is read only. Packaging uses its own pack_plugin.py.
"""
import argparse
import ast
import json
import os
from pathlib import Path
import re
import runpy
import shutil
import string
import subprocess
import sys
import tomllib
from collections import Counter

ROOT = Path(__file__).resolve().parents[1]
PACK = ROOT / "examples/plugins/zh_hans"


def write_table(path, values):
    path.write_text("# UTF-8; generated by scripts/build_zh_hans_plugin.py\n" + "".join(
        f"{json.dumps(key, ensure_ascii=False)} = {json.dumps(value, ensure_ascii=False)}\n"
        for key, value in sorted(values.items())), encoding="utf-8")


def fields(value):
    return Counter((name, spec, conversion) for _, name, spec, conversion
                   in string.Formatter().parse(value) if name is not None)


def document_text(source, translations):
    """Localize display metadata; parent IDs and Markdown anchors keep upstream identities."""
    text = source.read_text(encoding="utf-8")
    header = re.match(r"---\n(.*?)\n---\n", text, re.S)
    if not header:
        return text
    title = re.search(r"(?m)^title: (.+)$", header[1])
    if not title:
        return text
    if title[1] not in translations:
        raise ValueError(f"Missing document title: {source.name}: {title[1]}")
    start = header.start(1) + title.start(1)
    end = header.start(1) + title.end(1)
    return text[:start] + translations[title[1]] + text[end:]


def legacy_templates():
    """Migrate only the old regex rules expressible as literal-delimited API templates."""
    tree = ast.parse((ROOT / "gui/localization.py").read_text(encoding="utf-8"))
    rules = next(ast.literal_eval(node.value) for node in ast.walk(tree)
                 if isinstance(node, ast.Assign) and any(isinstance(t, ast.Name) and t.id == "patterns"
                                                        for t in node.targets))
    result = {}
    group = re.compile(r"\(\.\+\??\)|\(\.\*\)|\(\\d\+\)|\(\[\\d,\]\+\)")
    for pattern, target in rules:
        matches = list(group.finditer(pattern))
        if not matches:
            continue
        literals = group.split(pattern)
        if any(re.search(r"(?<!\\)[()\[\]*+?|^$]", literal) for literal in literals):
            continue
        source, position = "", 0
        names = []
        for index, match in enumerate(matches, 1):
            name = f"value{index}"
            names.append(name)
            source += re.sub(r"\\(.)", r"\1", pattern[position:match.start()]) + "{" + name + "}"
            position = match.end()
        source += re.sub(r"\\(.)", r"\1", pattern[position:])
        translated = re.sub(r"\\([1-9])", lambda m: "{" + names[int(m[1]) - 1] + "}", target)
        if fields(source) == fields(translated) and not re.search(r"\}\{", source):
            result[source] = translated
    return result


def build(upstream):
    PACK.mkdir(parents=True, exist_ok=True)
    old = tomllib.loads((ROOT / "pokeldn/app/data/strings.zh-Hans.toml").read_text(encoding="utf-8"))
    old_en = tomllib.loads((ROOT / "pokeldn/app/data/strings.en.toml").read_text(encoding="utf-8"))
    english = tomllib.loads((upstream / "pokeldn/app/data/strings.en.toml").read_text(encoding="utf-8"))
    labels = runpy.run_path(str(ROOT / "gui/zh_hans.py"))
    advanced = runpy.run_path(str(ROOT / "gui/advanced_zh_hans.py"))
    overrides = tomllib.loads((PACK / "overrides.toml").read_text(encoding="utf-8"))
    by_text = {value: old[key] for key, value in old_en.items() if key in old}
    by_text.update(labels["LABELS"])
    by_text.update(overrides)
    game_terms = json.loads((PACK / "pkhex_terms.json").read_text(encoding="utf-8"))["terms"]
    extra_terms = tomllib.loads((PACK / "term_overrides.toml").read_text(encoding="utf-8"))
    strings, missing = {}, {}
    for key, default in english.items():
        translated = overrides.get(default, old.get(key, by_text.get(default)))
        if translated is None:
            missing[key] = default
        elif fields(default) != fields(translated):
            raise ValueError(f"Placeholder mismatch: {key}: {default!r} -> {translated!r}")
        else:
            strings[key] = translated
    if missing:
        print(json.dumps(missing, ensure_ascii=False, indent=2))
        raise SystemExit(f"Translate {len(missing)} missing strings in {PACK / 'overrides.toml'}")
    strings.update(tomllib.loads((PACK / "context_strings.toml").read_text(encoding="utf-8")))
    write_table(PACK / "strings.toml", strings)
    messages = {**by_text, **game_terms, **extra_terms, **overrides}
    glossary = json.loads((ROOT / "docs/zh-Hans-glossary.json").read_text(encoding="utf-8"))
    terms = {**glossary["terms"], **labels["SPECIES"], **labels["LABELS"], **game_terms, **extra_terms}
    terms = {key: value for key, value in terms.items() if 0 < len(key) <= 200}
    write_table(PACK / "terms.toml", terms)
    # Archive labels are literal module messages; pair item IDs with PKHeX names at export time.
    messages.update(json.loads((PACK / "event_messages.json").read_text(encoding="utf-8")))
    write_table(PACK / "messages.toml", messages)
    templates = legacy_templates()
    templates.update(tomllib.loads((PACK / "template_overrides.toml").read_text(encoding="utf-8")))
    write_table(PACK / "templates.toml", templates)
    code = '''import json
from pokeldn.app.catalog import GAMES
from pokeldn.app.introspect import flags_of
print(json.dumps([(t.key, f.option, f.help) for g in GAMES for t in g.tools for f in flags_of(t.script)]))
'''
    env = {**os.environ, "POKELDN_PLUGINS": "", "PYTHONIOENCODING": "utf-8"}
    flags = json.loads(subprocess.check_output([sys.executable, "-c", code], cwd=upstream, env=env, text=True))
    help_text = {}
    help_overrides = tomllib.loads((PACK / "help_overrides.toml").read_text(encoding="utf-8"))
    missing_help = {}
    for tool, flag, default in flags:
        normalized = " ".join(default.split())
        key = f"{tool}:{flag}"
        translated = help_overrides.get(key, overrides.get(normalized, advanced["HELP"].get(normalized,
                     advanced["OPTION_HELP"].get(flag, by_text.get(normalized)))))
        if translated:
            help_text[key] = translated
        elif default:
            missing_help[key] = default
    write_table(PACK / "help.toml", help_text)
    docs = PACK / "docs"
    docs.mkdir(exist_ok=True)
    for source in (ROOT / "docs/zh-Hans").glob("*.md"):
        (docs / source.name).write_text(document_text(source, by_text), encoding="utf-8")
    shutil.copyfile(ROOT / "gui/guide.md", docs / "guide.md")
    revision = subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=upstream, text=True).strip()
    report = {"upstream_revision": revision, "strings": len(strings), "messages": len(messages),
              "terms": len(terms), "templates": len(templates), "help": len(help_text),
              "documents": len(list(docs.glob("*.md"))), "untranslated_help": missing_help}
    (PACK / "coverage.json").write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({k: v for k, v in report.items() if k != "untranslated_help"}, ensure_ascii=False))
    print(f"Advanced help falling back to English: {len(missing_help)}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--upstream", type=Path, required=True)
    build(parser.parse_args().upstream.resolve())
