"""The arena's ports of Scarlet 4.0.0's SDK heap setup, pinned to the words the SDK's own code wrote when
run under unicorn from empty memory (scratchpad/battle/arena/sdkrun.py): the page heap's initialisation
0x518b388 in both modes, and TinyMT32 init_by_array 0x525eefc."""
import pytest

from pokeldn.sv.battle.engine import arena

START = 0x40000000

# 0x518b388(START, START, size, commit): every nonzero u64 the SDK wrote in [START, START + size)
SDK_HEAP_INIT = {
    (0, 0x200000): {
        0x0: 0x200, 0x8: 0x40000A48, 0x10: 0x40001A48, 0x20: 0x4000000000001, 0x28: 0x40000, 0x30: 0x1,
        0x50: 0x40002000, 0x858: 0x40002090, 0x878: 0x8000000000000000, 0xA48: 0x40002100,
        0xA50: 0x40002100, 0xA58: 0x40002020, 0xA60: 0x40002090, 0x1A40: 0x40002090, 0x2008: 0x40000050,
        0x2010: 0xC00000001FFFFFFF, 0x2018: 0x10021, 0x2030: 0x3000000, 0x2038: 0x40002000, 0x2040: 0x1,
        0x2098: 0x40000858, 0x20A0: 0x2000000, 0x20A8: 0x40003000, 0x20B0: 0x1FD, 0x2110: 0x3000000,
        0x2118: 0x40000000, 0x2120: 0x2,
    },
    (1, 0x1000000): {
        0x0: 0x1000, 0x8: 0x40000A48, 0x10: 0x40008A48, 0x18: 0x40009A48, 0x20: 0x20000000000001,
        0x28: 0x100200000, 0x30: 0x1, 0x50: 0x4000A000, 0x858: 0x4000A090, 0x878: 0x8000000000000000,
        0xA48: 0x4000A100, 0xA90: 0x4000A100, 0xA98: 0x4000A020, 0xAA0: 0x4000A090, 0x8A40: 0x4000A090,
        0x9A48: 0x1, 0xA008: 0x40000050, 0xA010: 0xC00000001FFFFFFF, 0xA018: 0x10021, 0xA030: 0x3000000,
        0xA038: 0x4000A000, 0xA040: 0x1, 0xA098: 0x40000858, 0xA0A0: 0x2000000, 0xA0A8: 0x4000B000,
        0xA0B0: 0xFF5, 0xA110: 0x3000000, 0xA118: 0x40000000, 0xA120: 0xA,
    },
}


@pytest.mark.parametrize("commit,size", sorted(SDK_HEAP_INIT))
def test_heap_init_writes_what_the_sdk_writes(commit, size):
    m = arena.Arena()
    assert arena._heap_init(m, START, START, size, commit) == 0
    words = {}
    for page, data in m.pages.items():
        for i in range(0, 0x1000, 8):
            w = int.from_bytes(data[i:i + 8], "little")
            if w:
                words[page + i - START] = w
    assert words == SDK_HEAP_INIT[(commit, size)]


@pytest.mark.parametrize("key,state", [
    (bytes(16), (0x155ECC50, 0xEA31243D, 0x3C4D2E49, 0x1BA8914A)),
    (bytes(range(16)), (0x8605874D, 0x03CF774F, 0xED0803D7, 0xC9BCFB5E)),
])
def test_generator_seeding_matches_the_sdk(key, state):
    words = [int.from_bytes(key[i:i + 4], "little") for i in range(0, 16, 4)]
    assert tuple(arena.tinymt_init(words)) == state
